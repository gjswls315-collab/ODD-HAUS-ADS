// Walk through every menu screen with real keyboard input and screenshot each one.
// usage: node scripts/screens.mjs <url> <outDir> [width] [height]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const [url = 'http://localhost:5173/', out = './screens', w = '1920', h = '1080'] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e.stack || e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const wait = (ms) => page.waitForTimeout(ms);
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
const press = async (k, ms = 400) => { await page.keyboard.press(k); await wait(ms); };
const scene = () => page.evaluate(() => { const s = window.__ER.scenes.current; return s.w && s.hud ? 'GameScene' : s.constructor.name; });

await page.goto(url);
await page.evaluate(() => localStorage.clear());
await page.reload();
await wait(5600);
await shot('01_intro');
await press('Enter', 1200);
await shot('02_title');
console.log('after intro:', await scene());
await press('Enter', 1700);
await shot('03_prologue');
console.log('after start:', await scene());
await press('Enter', 300);
await press('Enter', 1500);
await shot('03b_prologue2');
await page.keyboard.down('Escape');
await wait(1300);
await page.keyboard.up('Escape');
await wait(1600);
console.log('after skip:', await scene());
await wait(1500);
await shot('04_select');
await press('ArrowRight', 900);
await press('Tab', 300);
await wait(2500);
await shot('05_select_noctis');
await press('Tab', 300);
await press('ArrowLeft', 600);
await press('Enter', 2200);
console.log('after confirm:', await scene());
await shot('06_howto');
await press('Enter', 2600);
await shot('07_preview');
await press('Enter', 1600);
console.log('after begin:', await scene());
await wait(1600);
await shot('08_game_start');
await press('Escape', 500);
await shot('09_pause');
await press('ArrowDown', 200);
await press('ArrowDown', 200);
await press('ArrowDown', 200);
await press('Enter', 600);
await shot('10_options');
await press('Escape', 400);
await press('ArrowUp', 200);
await press('Enter', 500);
await shot('11_controls');
await press('Escape', 400);
await press('Escape', 800);
console.log('resumed mode:', await page.evaluate(() => window.__ER.scenes.current.mode));
// force a game over
await page.evaluate(() => {
  const p = window.__ER.scenes.current.w.player;
  p.lives = 1; p.invuln = 0; p.hp = 1;
  p.hit();
});
await wait(5200);
await shot('12_gameover');
console.log('mode:', await page.evaluate(() => window.__ER.scenes.current.mode));
await press('ArrowRight', 300);
await press('Enter', 2600);
await shot('13_record');
console.log('final:', await scene());
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
await browser.close();
