"""Cut the JEON DE VERO marks out of the client's logo sheet for the film.

Each mark is separated from the cream paper by flood-filling the paper from the crop border
(through every pixel that is not ink), so a mark's own cream fills (cap crown, badge text,
skin) stay. Output: src/assets/jdvArt.js (PNG data URIs) + tools/out_art/*.png for review.

    python3 tools/extract_art.py
"""
import base64, io, json, pathlib
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHEET = ROOT / "reference" / "jdv_logo_sheet.webp"
POSTER = ROOT / "reference" / "jdv_skate_poster.webp"
OUT = ROOT / "tools" / "out_art"

# name: (crop box on the sheet, polygons to erase before the fill (crop coords), upscale)
MARKS = {
    "head": ((35, 14, 362, 306), [[(278, 0), (327, 0), (327, 196), (300, 196), (284, 120)], [(298, 250), (327, 250), (327, 292), (290, 292)]], 2),
    "peek": ((536, 404, 984, 694), [], 2),
    "oval": ((1088, 92, 1504, 372), [], 2),
    "sign": ((32, 412, 503, 688), [], 2),
    "rect": ((1012, 712, 1506, 1008), [], 2),
    "bubble": ((1032, 420, 1508, 708), [], 2),
    "pennant": ((28, 716, 506, 1012), [], 2),
    "bold": ((505, 732, 968, 966), [], 2),
}

CLOSE = {"rect": 7, "bubble": 7, "sign": 3, "oval": 3, "pennant": 3}

def is_ink(a):
    r, g, b = a[..., 0].astype(float), a[..., 1].astype(float), a[..., 2].astype(float)
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    sat = (np.max(a, -1).astype(float) - np.min(a, -1)) / 255
    navy = lum < 120
    red = (r > 110) & (g < r * 0.62) & (lum < 175)
    return navy | red | (sat > 0.42)

def cut(name, box, erase, up):
    im = Image.open(SHEET).convert("RGB").crop(box)
    if erase:
        d = ImageDraw.Draw(im)
        for poly in erase:
            d.polygon(poly, fill=(250, 233, 207))
    a = np.asarray(im)
    ink = is_ink(a)
    # paper = non-ink pixels connected to the border; thin distressed outlines are closed first
    barrier = Image.fromarray(np.where(ink, 255, 0).astype(np.uint8))
    if CLOSE.get(name, 0) >= 3:
        barrier = barrier.filter(ImageFilter.MaxFilter(CLOSE[name]))
    free = Image.fromarray(255 - np.asarray(barrier))
    pad = Image.new("L", (free.width + 2, free.height + 2), 255)
    pad.paste(free, (1, 1))
    ImageDraw.floodfill(pad, (0, 0), 128)
    outside = np.asarray(pad)[1:-1, 1:-1] == 128
    alpha = Image.fromarray(np.where(outside, 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(0.7))
    rgba = im.convert("RGBA")
    rgba.putalpha(alpha)
    rgba = rgba.resize((im.width * up, im.height * up), Image.LANCZOS)
    rgba.save(OUT / f"{name}.png")
    return rgba

# The head faces screen-right; when he turns the other way the film shows it mirrored. A plain mirror
# would print "VDJ" on his cap, so the mirrored head carries the cap lettering un-mirrored and re-tilted
# to sit on the mirrored crown.
CAP_LETTERS = [(236, 96), (372, 44), (424, 48), (436, 132), (292, 204), (246, 210)]   # in head pixels (after ×2)
CAP_TILT = 19.0                                                                         # degrees the lettering rises to the right

def mirror_head(img):
    import numpy as np
    from PIL import ImageDraw, ImageFilter, ImageOps
    a = np.array(img).astype(np.float32)
    luma = 0.3 * a[..., 0] + 0.59 * a[..., 1] + 0.11 * a[..., 2]
    poly = Image.new("L", img.size, 0); ImageDraw.Draw(poly).polygon(CAP_LETTERS, fill=255)
    inside = np.array(poly) > 0
    letters = inside & (luma < 120) & (a[..., 3] > 128)
    grow = np.array(Image.fromarray((letters * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(5))) > 0
    cream = np.median(a[inside & (luma > 170)][:, :3], axis=0)
    flipped = np.array(ImageOps.mirror(img)).astype(np.float32)
    gm = grow[:, ::-1]
    flipped[gm, :3] = cream
    out = Image.fromarray(flipped.clip(0, 255).astype(np.uint8), "RGBA")
    # the lettering itself, soft-edged, un-mirrored, tilted the other way, at the mirrored spot
    alpha = (np.clip((190 - luma) / 70, 0, 1) * grow * 255).astype(np.uint8)
    layer = np.array(img).copy(); layer[..., 3] = alpha
    ys, xs = np.where(grow)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    piece = Image.fromarray(layer, "RGBA").crop((x0, y0, x1, y1)).rotate(-2 * CAP_TILT, resample=Image.BICUBIC, expand=True)
    cx, cy = img.width - (x0 + x1) / 2, (y0 + y1) / 2
    out.alpha_composite(piece, (int(round(cx - piece.width / 2)), int(round(cy - piece.height / 2))))
    return out

def uri(img, fmt="WEBP"):
    b = io.BytesIO(); img.save(b, fmt, quality=90, method=6) if fmt == "WEBP" else img.save(b, fmt, quality=88)
    return f"data:image/{fmt.lower()};base64," + base64.b64encode(b.getvalue()).decode()

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    js = ["// Generated by tools/extract_art.py from reference/jdv_logo_sheet.webp and jdv_skate_poster.webp. Do not edit."]
    meta = {}
    for name, (box, erase, up) in MARKS.items():
        img = cut(name, box, erase, up)
        meta[name] = img.size
        js.append(f'export const {name.upper()} = "{uri(img)}";')
        if name == "head":
            hm = mirror_head(img); hm.save(OUT / "head_m.png")
            js.append(f'export const HEAD_M = "{uri(hm)}";')
    poster = Image.open(POSTER).convert("RGB").resize((561, 701), Image.LANCZOS)
    js.append(f'export const POSTER = "{uri(poster, "JPEG")}";')
    js.append(f"export const ART_META = {json.dumps(meta)};")
    (ROOT / "src" / "assets" / "jdvArt.js").write_text("\n".join(js) + "\n")
    print("wrote", (ROOT / "src/assets/jdvArt.js").stat().st_size // 1024, "KB", meta)

if __name__ == "__main__":
    main()
